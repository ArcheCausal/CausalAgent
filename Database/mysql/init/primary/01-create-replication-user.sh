#!/bin/bash
set -eu

# 所有密码只来自服务器上的单个密钥文件；官方入口变量由 mysql-secret-entrypoint.sh 导出。
. /opt/causalagent/secret-env.sh

APP_WRITE_USER="${MYSQL_WRITE_USER:-${MYSQL_USER:-}}"
APP_READ_USER="${MYSQL_READ_USER:-${MYSQL_USER:-}}"
APP_WRITE_PASSWORD="$(secret_value MYSQL_WRITE_PASSWORD)"
APP_READ_PASSWORD="$(secret_value MYSQL_READ_PASSWORD)"
REPLICATION_USER="${MYSQL_REPLICATION_USER:-replica}"
REPLICATION_PASSWORD="$(secret_value MYSQL_REPLICATION_PASSWORD)"

mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE USER IF NOT EXISTS '${APP_WRITE_USER}'@'%' IDENTIFIED BY '${APP_WRITE_PASSWORD}';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, DROP, REFERENCES ON \`${MYSQL_DATABASE}\`.* TO '${APP_WRITE_USER}'@'%';
CREATE USER IF NOT EXISTS '${APP_READ_USER}'@'%' IDENTIFIED BY '${APP_READ_PASSWORD}';
GRANT SELECT ON \`${MYSQL_DATABASE}\`.* TO '${APP_READ_USER}'@'%';
GRANT SELECT ON performance_schema.events_statements_summary_by_digest TO '${APP_READ_USER}'@'%';
CREATE USER IF NOT EXISTS '${REPLICATION_USER}'@'%' IDENTIFIED BY '${REPLICATION_PASSWORD}';
GRANT REPLICATION SLAVE, REPLICATION CLIENT ON *.* TO '${REPLICATION_USER}'@'%';
SQL

if [ -n "${MYSQL_REPLICA_STATUS_USER:-}" ] && secret_value MYSQL_REPLICA_STATUS_PASSWORD >/dev/null 2>&1; then
  STATUS_PASSWORD="$(secret_value MYSQL_REPLICA_STATUS_PASSWORD)"
  mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE USER IF NOT EXISTS '${MYSQL_REPLICA_STATUS_USER}'@'%' IDENTIFIED BY '${STATUS_PASSWORD}';
GRANT REPLICATION CLIENT ON *.* TO '${MYSQL_REPLICA_STATUS_USER}'@'%';
FLUSH PRIVILEGES;
SQL
else
  mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
FLUSH PRIVILEGES;
SQL
  echo "MYSQL_REPLICA_STATUS_USER or its password is not set; replica status account was not created" >&2
fi
