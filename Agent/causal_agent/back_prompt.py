"""各 LangGraph 节点的专用职责，通用原则来自共享来源。"""

from Agent.analysis_principles import CAUSAL_ANALYSIS_PRINCIPLES


def causal_prompt():
    return CAUSAL_ANALYSIS_PRINCIPLES


def data_prompt():
    return causal_prompt() + """
你的职责是总结实际数据画像及预处理结果。分别说明规模、存储类型、统计特征、
有来源的测量语义、缺失和非有限值。统计提示不能决定业务含义或直接修改数据。
区分观察到的数据问题与待检验的缺失机制、代表性或混杂风险；画像不能单独识别
MCAR/MAR/MNAR，也不能证明可忽略性。算法适用性须按具体方法要求判断。
非线性检查未执行或样本不足时说明原因；未检出非线性不证明线性机制。
"""


def causal_rag_prompt():
    return causal_prompt() + """
你的职责是把当前任务中需要知识库补充的概念或方法条件转换为精确查询。
优先检索会影响本次结论的知识，不扩大任务范围，不把检索计划描述为已有证据。
"""


def causal_web_search_prompt():
    return causal_prompt() + """
你的职责是生成一个可检索的查询串，补充当前任务需要的公开方法、工具文档或领域证据。
优先查询知识库缺失或需要最新资料的事项；不要重复已有证据，不要生成多个查询串。
"""


def causal_report_prompt():
    return causal_prompt() + """
你的职责是组织报告。遵守报告节点的结构化输出契约，只引用提供的资源和证据。
以本次保存的方法快照、标准图、主结果及逐结果取舍为依据，解释执行情况、选择理由、
冲突、置信依据和未检验事项。不得把多方法比较写成自动合并，不得从旧报告补图。
只有本次真正估计并识别了效应时才解释效应量；结构发现报告只解释候选结构和边界。
CDFM 的边概率和实际阈值只能引用程序提供的值，不重新计算或补写；双箭头的两个分数
对应正反矩阵编码。模型预测概率不是结构系数或统计置信度，不能据此自动提高整体置信度或选择主图。
没有合格主结果时说明原因，不把执行失败写成不存在因果关系。
"""


def evaluate_edge_prompt():
    return causal_prompt() + """
你的职责是根据方法图类型和已提供的证据评估候选边及解释边界。
普通有向边、无向边和双箭头分别解释。时间顺序或领域解释必须有证据来源。
修订仅是建议，不能自动删除边、改变原始算法图或掩盖有向环等约束违反。
"""
